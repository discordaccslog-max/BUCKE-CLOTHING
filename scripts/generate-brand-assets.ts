/**
 * Builds every brand asset from the master mark at public/buck.svg.
 * Run after replacing that file:
 *
 *   npm run brand
 *
 * Writes:
 *   src/components/brand/buck-paths.ts  path data for the hero (full mark)
 *                                       and the simplified mark
 *   public/buck-mark.svg                simplified mark: antlers + nose only
 *   src/app/icon.svg, src/app/favicon.ico (16/32/48)
 *
 * The full mark is too detailed below ~64px, so everything small (favicon,
 * header, OG image) uses the simplified variant.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const INK = "#0e0e0d";
const BONE = "#f3f0ea";
const root = join(import.meta.dirname, "..");

/** DOM order in buck.svg: nose, face, inner antlers, lower sweeps, outer tips. */
const NAMES = [
  "nose",
  "face",
  "antler-inner-left",
  "antler-inner-right",
  "antler-low-left",
  "antler-low-right",
  "antler-outer-left",
  "antler-outer-right",
] as const;
const SIMPLIFIED = NAMES.filter((n) => n !== "face");

const source = readFileSync(join(root, "public/buck.svg"), "utf8");
const found = [...source.matchAll(/<path\s+class="buck-([^"]+)"\s+d="([^"]+)"\s*\/>/g)].map((m) => ({
  name: m[1],
  d: m[2].trim(),
}));
const order = found.map((p) => p.name).join(",");
if (order !== NAMES.join(",")) {
  throw new Error(`public/buck.svg: expected paths ${NAMES.join(", ")} in that order, found ${order}`);
}

/** Bounding box from every coordinate pair (control points included: slightly generous). */
function bbox(paths: { d: string }[]) {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const { d } of paths) {
    const nums = d.match(/-?\d*\.?\d+/g)!.map(Number);
    for (let i = 0; i + 1 < nums.length; i += 2) {
      minX = Math.min(minX, nums[i]); maxX = Math.max(maxX, nums[i]);
      minY = Math.min(minY, nums[i + 1]); maxY = Math.max(maxY, nums[i + 1]);
    }
  }
  return { minX, minY, maxX, maxY };
}

/** Tight viewBox around the art with `pad` units on every side, so nothing crops. */
function viewBox(paths: { d: string }[], pad: number) {
  const b = bbox(paths);
  const r = (n: number) => Math.round(n);
  return `${r(b.minX - pad)} ${r(b.minY - pad)} ${r(b.maxX - b.minX + pad * 2)} ${r(b.maxY - b.minY + pad * 2)}`;
}

const full = found;
const simple = found.filter((p) => (SIMPLIFIED as readonly string[]).includes(p.name));
const fullBox = viewBox(full, 24);
const simpleBox = viewBox(simple, 24);

writeFileSync(
  join(root, "src/components/brand/buck-paths.ts"),
  `/**
 * GENERATED by scripts/generate-brand-assets.ts from public/buck.svg.
 * Do not edit by hand; replace public/buck.svg and run \`npm run brand\`.
 */

/** Full mark (hero only), 8 paths in DOM order. */
export const BUCK_VIEWBOX = ${JSON.stringify(fullBox)};
export const BUCK_PATHS = ${JSON.stringify(full, null, 2)} as const;

/** Simplified mark (antlers + nose) for small sizes: header, favicon, OG. */
export const BUCK_MARK_VIEWBOX = ${JSON.stringify(simpleBox)};
export const BUCK_MARK_PATHS = ${JSON.stringify(simple, null, 2)} as const;
`,
);

function simpleSvg(attrs = 'fill="currentColor"', extra = "") {
  const paths = simple.map((p) => `  <path class="buck-${p.name}" d="${p.d}"/>`).join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${simpleBox}" ${attrs} role="img" aria-label="Bucke">\n${extra}${paths}\n</svg>\n`;
}
writeFileSync(join(root, "public/buck-mark.svg"), simpleSvg());

// App icon: bone mark centred on an ink rounded square. The mark is wide,
// so it is fitted to the square's width with a margin.
function iconSvg(size: number) {
  const [x, y, w, h] = simpleBox.split(" ").map(Number);
  const side = Math.max(w, h) * 1.16;
  const ox = x - (side - w) / 2;
  const oy = y - (side - h) / 2;
  const radius = side * 0.16;
  const paths = simple.map((p) => `<path d="${p.d}"/>`).join("");
  // A hairline stroke in the same color thickens the antlers slightly so they
  // survive rasterising at 16-32px.
  const stroke = size <= 48 ? ` stroke="${BONE}" stroke-width="${(side / size) * 0.6}" stroke-linejoin="round"` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${ox} ${oy} ${side} ${side}" width="${size}" height="${size}"><rect x="${ox}" y="${oy}" width="${side}" height="${side}" rx="${radius}" fill="${INK}"/><g fill="${BONE}"${stroke}>${paths}</g></svg>`;
}
writeFileSync(join(root, "src/app/icon.svg"), iconSvg(512));

const sizes = [16, 32, 48];
const pngs = await Promise.all(sizes.map((s) => sharp(Buffer.from(iconSvg(s))).png().toBuffer()));
const header = Buffer.alloc(6);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(sizes.length, 4);
let offset = 6 + 16 * sizes.length;
const entries = sizes.map((s, i) => {
  const e = Buffer.alloc(16);
  e.writeUInt8(s, 0);
  e.writeUInt8(s, 1);
  e.writeUInt16LE(1, 4);
  e.writeUInt16LE(32, 6);
  e.writeUInt32LE(pngs[i].length, 8);
  e.writeUInt32LE(offset, 12);
  offset += pngs[i].length;
  return e;
});
writeFileSync(join(root, "src/app/favicon.ico"), Buffer.concat([header, ...entries, ...pngs]));

console.log(`Brand assets written. Full viewBox ${fullBox}; simplified ${simpleBox}.`);
