const VIEWS = ["front", "back", "detail"] as const;

function color(productSlug: string, productName: string, name: string, swatch: string): ProductColor {
  const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, "-");
  return {
    name,
    slug,
    swatch,
    images: VIEWS.map((view, i) => ({
      src: `/products/${productSlug}/${slug}-${i + 1}.svg`,
      alt: `${productName} in ${name}, ${view} view`,
      width: 1600,
      height: 2000,
    })),
  };
}

function product(
  p: Omit<Product, "colors" | "currency"> & { colors: [string, string][] },
): Product {
  return {
    ...p,
    currency: "USD",
    colors: p.colors.map(([name, swatch]) => color(p.slug, p.name, name, swatch)),
  };
}

